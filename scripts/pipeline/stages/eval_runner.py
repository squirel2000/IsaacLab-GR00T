"""EVAL stage — closed-loop IsaacSim eval on the H100, right after training.

Drives ``scripts/eval/run_eval.py`` DETACHED on Pegasus (eval runs for hours and must
survive a local disconnect, exactly like training), polls the per-run combined-episodes
log, parses the success rate, records it to pipeline state, and fetches the comparison
SVG for the report.

Gated by config ``eval.enabled`` (default false): until the H100 has this branch's
``scripts/eval`` plus its IsaacSim/policy-server conda envs, the stage is a NO-OP so the
rest of the pipeline (download → deploy → report) still runs. Flip ``eval.enabled: true``
once the H100 side is ready.
"""
from __future__ import annotations

import datetime
import os
import re
import shlex
import threading
import time

import pegasus as pg
import run_finetune as rf
import pipeline_config as pc
import pipeline_progress as pp
from gpu_monitor import connect_with_retry
from pipeline_logging import get_logger
from pipeline_paths import LOGS_DIR

log = get_logger("eval")

# Same per-episode line as scripts/eval/analysis/aggregate.py:
#   "Episode N finished after S steps (Success: True/False, ...)"
_EP = re.compile(r"Success:\s*(True|False)")


# --------------------------------------------------------------------------- #
#  Pure helpers (unit-tested)
# --------------------------------------------------------------------------- #
def parse_eval_log(text: str) -> dict:
    """Count episodes + successes in a combined-episodes log → {n, success, rate}."""
    n = succ = 0
    for line in text.splitlines():
        m = _EP.search(line)
        if m:
            n += 1
            succ += m.group(1) == "True"
    return {"n": n, "success": succ, "rate": (succ / n if n else 0.0)}


def build_eval_config(config: dict, output_dir: str, run_name: str) -> str:
    """Render a one-run ``eval_config.yaml`` (YAML text) pointing at the trained checkpoint.

    Pure: takes the config's ``eval`` knobs + the checkpoint dir, returns YAML. run_eval.py
    resolves a parent dir to its latest ``checkpoint-*`` automatically.
    """
    import yaml
    ev = config.get("eval", {}) or {}
    spec = {
        "defaults": {
            "task": ev.get("task", "Isaac-Can-Sorting-OpenArm-DexHand-v0"),
            "target": int(ev.get("target_episodes", 100)),
            "max_attempts": int(ev.get("max_attempts", 12)),
            "jobs": 1,
            "headless": True,
            "save_video": bool(ev.get("save_video", False)),
            "filter": True,
            "multitask": True,
            "pov_list": ["head"],
            "openarm_hand_type": ev.get("openarm_hand_type", "linkerhand_o6"),
            "client_timeout_s": int(ev.get("client_timeout_s", 14400)),
            "server_ready_timeout_s": int(ev.get("server_ready_timeout_s", 900)),
            "server_ready_string": "Server is ready and listening",
            "logdir": "output/eval/logs",
        },
        "env": {
            "isaaclab_repo": ev.get("isaaclab_repo", "IsaacLab"),
            "isaaclab_conda_env": ev.get("isaaclab_conda_env", "env_isaaclab"),
            "conda_sh": ev.get("conda_sh", "") or "",
        },
        "runs": [{
            "tag": run_name, "policy": "gr00t",
            "config": ev.get("backend_config", "scripts/eval/configs/gr00t_n17_openarm_o6.json"),
            "save_id": run_name, "checkpoint": str(output_dir),
        }],
    }
    return yaml.safe_dump(spec, sort_keys=False)


def _h100_repo_root(config: dict, profile: dict) -> str:
    """Superproject root on the H100 (holds scripts/eval) = parent of the n1d7 train_cwd."""
    ev = config.get("eval", {}) or {}
    return str(ev.get("h100_repo_root") or os.path.dirname(str(profile["train_cwd"]).rstrip("/")))


def _eval_wrapper(repo_root: str, cfg_rel: str, state_abs: str, headless_logdir: str) -> str:
    """Detached server-side bash wrapper: run run_eval.py, record status + where logs land."""
    return f"""#!/bin/bash
# auto-generated by eval_runner.py
STATE={shlex.quote(state_abs)}
echo RUNNING > "$STATE/status"
{{
  echo "[eval] $(date '+%F %T') start"
  cd {shlex.quote(repo_root)} || {{ echo FAILED_CD > "$STATE/status"; exit 11; }}
  echo "{headless_logdir}" > "$STATE/logdir"
  python3 scripts/eval/run_eval.py --config {shlex.quote(cfg_rel)}
  rc=$?
  if [ $rc -ne 0 ]; then echo "FAILED_EVAL:$rc" > "$STATE/status"; exit $rc; fi
  echo DONE > "$STATE/status"
  echo "[eval] all done $(date '+%F %T')"
}} >> "$STATE/run.log" 2>&1
"""


# --------------------------------------------------------------------------- #
#  Live operations
# --------------------------------------------------------------------------- #
def preflight(s, repo_root: str) -> None:
    """Fail fast (with guidance) if the H100 doesn't have this branch's eval harness."""
    out, rc = pg.sh(s, f"test -f {shlex.quote(repo_root)}/scripts/eval/run_eval.py "
                       f"&& echo ok || echo missing", timeout=60)
    if "ok" not in out:
        raise SystemExit(
            f"eval harness not found on the H100 ({repo_root}/scripts/eval/run_eval.py).\n"
            f"  Push this branch and `git pull` it on the H100 (and ensure the IsaacSim /\n"
            f"  policy-server conda envs exist), or set eval.enabled=false to skip EVAL.")


def run(config: dict, state) -> None:
    """EVAL stage entry point. No-op when eval.enabled is false."""
    ev = config.get("eval", {}) or {}
    if not ev.get("enabled", False):
        log.info("EVAL disabled (config eval.enabled=false) — skipping closed-loop eval.")
        state.record_outputs(eval_skipped=True)
        return

    _, profile = pc.resolve_profile(config, state.profile)
    output_dir = state.get("output_dir") or str(profile["output_dir"])
    run_name = os.path.basename(str(output_dir).rstrip("/"))
    repo_root = _h100_repo_root(config, profile)

    s = connect_with_retry(config)
    preflight(s, repo_root)

    # Reuse the recorded eval state dir if resuming; else create + launch detached.
    state_abs = state.get("eval_state_abs")
    if not state_abs or rf.read_text(s, pg.relpath(state_abs) + "/status") != "RUNNING":
        runid = f"{run_name}_eval_" + datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
        state_abs = f"{config['pegasus']['state_root']}/{runid}"
        state_rel = pg.relpath(state_abs)
        cfg_rel = f"{state_rel}/eval_config.yaml"
        state.record_outputs(eval_state_abs=state_abs)
        pg.put_file(s, rf._tmp_write(build_eval_config(config, output_dir, run_name),
                                     "eval_config.yaml"), cfg_rel)
        logdir = f"{repo_root}/output/eval/logs_headless"
        pg.put_file(s, rf._tmp_write(_eval_wrapper(repo_root, cfg_rel, state_abs, logdir),
                                     "eval_wrapper.sh"), f"{state_rel}/eval_wrapper.sh")
        launch = (f"cd {shlex.quote(state_abs)} && : > run.log && "
                  f"nohup setsid bash eval_wrapper.sh >/dev/null 2>&1 & echo started")
        threading.Thread(target=lambda: pg.sh(s, launch, timeout=90), daemon=True).start()
        log.info("Launched closed-loop eval (detached) for %s; this runs for a while.", run_name)
    else:
        log.info("Re-attaching to running eval %s", state_abs)

    rel = pg.relpath(state_abs)
    target = int(ev.get("target_episodes", 100))
    poll = int(config["training"]["monitor_interval_sec"])
    combined = f"{repo_root}/output/eval/logs_headless/{run_name}_combined_episodes.log"
    while True:
        agg = parse_eval_log(rf.fetch(s, pg.relpath(combined), 0).decode("utf-8", "replace"))
        status = rf.read_text(s, f"{rel}/status")
        pp.update("eval", done=agg["n"], total=target,
                  pct=(round(100 * agg["n"] / target, 1) if target else None),
                  success_rate=round(agg["rate"], 4), status=status)
        log.info("[%s] eval %d/%d episodes, success_rate=%.1f%%",
                 status or "?", agg["n"], target, 100 * agg["rate"])
        if status == "DONE" or agg["n"] >= target:
            state.record_outputs(eval_episodes=agg["n"], eval_success=agg["success"],
                                 eval_success_rate=round(agg["rate"], 4))
            break
        if status.startswith("FAILED"):
            raise RuntimeError(f"closed-loop eval {status} — see {combined} on the H100")
        time.sleep(poll)

    # Fetch the comparison chart for the offline report (best-effort).
    try:
        svg = rf.fetch(s, pg.relpath(f"{repo_root}/output/analysis/eval_results_headless.svg"), 0)
        if svg:
            LOGS_DIR.mkdir(exist_ok=True)
            (LOGS_DIR / "eval_results.svg").write_bytes(svg)
            state.record_outputs(eval_chart="logs/eval_results.svg")
    except Exception as e:                           # noqa: BLE001
        log.warning("could not fetch eval chart: %s", e)
    log.info("EVAL done: %d episodes, success_rate=%.1f%%",
             state.get("eval_episodes") or 0, 100 * (state.get("eval_success_rate") or 0))
